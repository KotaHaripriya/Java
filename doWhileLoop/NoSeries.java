package doWhileLoop;

public class NoSeries {
    public static void main(String[] args) {
        int i = 10;
        do {
            System.out.println(i);
            i--;

        } while (i >= 1);
        System.out.println();
        int a = 1;
        do {
            System.out.println(a * a);
            a++;
        } while (a <= 10);

    }

}
