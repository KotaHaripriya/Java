package Problems_on_ifElse;

public class ifElse {
    public static void main(String[] args) {
          int i = 23, j = 14, k=16 ;

    if(i>j && i>k)
    {
        System.out.println("i is greater than j & k");
    }else if(j>k)
    {
        System.out.println("j is greater than i & k");
    }else
    {
        System.out.println("k is greater than i & j");
    }
    }
  

}
